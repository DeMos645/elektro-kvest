function miniGame() {
  if (!canEarn()) return;
  miniTried = qi;
  renderLifelines();
  const items = shuffle(TRUE_OR_MYTH).slice(0, 3);
  let k = 0;
  const box = el(`<div class="modal-bg"><div class="modal mini">
    <div class="mini-h">⚡ Правда чи міф?</div>
    <p class="mini-sub">Дай 3 правильні відповіді поспіль — і поверни собі підказку.</p>
    <div class="mini-dots">${items.map(() => '<i></i>').join('')}</div>
    <div class="mini-card" id="mini-card"></div>
    <div class="row" id="mini-btns"><button class="btn mini-true" data-a="1">✔ Правда</button><button class="btn mini-false" data-a="0">✖ Міф</button></div>
    <div id="mini-res"></div></div></div>`);
  document.body.appendChild(box);
  const mcard = box.querySelector('#mini-card'), dots = box.querySelectorAll('.mini-dots i');
  const res = box.querySelector('#mini-res'), btns = box.querySelector('#mini-btns');
  const close = () => { box.remove(); renderLifelines(); };
  const showItem = () => { mcard.textContent = items[k].t; mcard.classList.remove('enter'); void mcard.offsetWidth; mcard.classList.add('enter'); };
  showItem();

  btns.onclick = e => {
    const b = e.target.closest('[data-a]');
    if (!b || btns.dataset.busy) return;
    btns.dataset.busy = '1';
    const ok = (b.dataset.a === '1') === items[k].a;
    dots[k].className = ok ? 'ok' : 'bad';
    res.innerHTML = `<div class="mini-why ${ok ? 'ok' : 'bad'}">${ok ? '✅' : '❌'} ${items[k].why}</div>`;
    if (!ok) {
      btns.hidden = true;
      res.innerHTML += `<p class="mini-sub">Цього разу не вийшло. Спробуй ще раз на наступному питанні!</p>
        <div class="row"><button class="btn" id="mini-close">Повернутися до питання</button></div>`;
      box.querySelector('#mini-close').onclick = close;
      return;
    }
    // правильно — ховаємо «Правда/Міф» і чекаємо, поки учень прочитає пояснення й натисне «Далі»
    btns.hidden = true;
    const lastOne = k === items.length - 1;
    res.innerHTML += `<div class="row" style="margin-top:14px"><button class="btn" id="mini-next">${lastOne ? 'Забрати підказку →' : 'Далі →'}</button></div>`;
    const nextBtn = box.querySelector('#mini-next');
    nextBtn.focus();
    nextBtn.onclick = () => {
      delete btns.dataset.busy;
      if (++k < items.length) { res.innerHTML = ''; btns.hidden = false; showItem(); return; }
      // перемога — обираємо, яку підказку повернути
      btns.hidden = true; mcard.hidden = true;
      const opts = [];
      if (used.fifty) opts.push(['fifty', '50:50']);
      if (used.hint) opts.push(['hint', '💡 Викладач']);
      if (used.swap < SWAPS) opts.push(['swap', '🔄 Інше питання']);
      res.innerHTML = `<p class="mini-win">🎉 Чудово! Обери, яку підказку повернути:</p>
        <div class="row">${opts.map(([id, name]) => `<button class="btn" data-back="${id}">${name}</button>`).join('')}</div>`;
      res.querySelectorAll('[data-back]').forEach(x => x.onclick = () => {
        const id = x.dataset.back;
        if (id === 'swap') used.swap++; else used[id] = false;
        close();
      });
    };
  };
}

/* ---------- Відповідь ---------- */
function answer(btn) {
  if (locked || btn.classList.contains('hidden')) return;
  locked = true;
  const Q = cur();
  const buttons = [...card.querySelectorAll('.ans')];
  buttons.forEach(b => b.disabled = true);
  btn.classList.add('pick');
  renderLadder();
  renderLifelines(); // після відповіді міні-гра недоступна

  // невелика пауза «для інтриги», як у телешоу
  setTimeout(() => {
    btn.classList.remove('pick');
    const right = buttons.find(b => b.dataset.v === Q.a);
    right.classList.add('right');
    const ok = btn === right;
    if (!ok) btn.classList.add('wrong');
    if (ok) score = PRIZES[qi];
    log.push({ q: Q.q, ok, a: Q.a });

    const last = qi === N - 1;
    document.getElementById('extra').innerHTML = `<div class="explain ${ok ? 'ok' : 'bad'}"><b>${ok ? '✅ Правильно!' : '❌ Неправильно.'}</b> ${Q.why}</div>
      <div class="row" style="margin-top:16px;justify-content:flex-start"><button class="btn" id="go">${ok && !last ? 'Наступне питання →' : 'Результат'}</button></div>`;
    renderLadder();
    const go = document.getElementById('go');
    go.focus();
    go.onclick = () => { if (ok && !last) { qi++; show(); } else finish(ok ? 'win' : 'lose'); };
  }, 1300);
}

/* ---------- Кінець гри ---------- */
function finish(mode) {
  const won = mode === 'win';
  const reached = log.filter(x => x.ok).length;
  let kept = score;
  if (mode === 'lose') {
    const safe = SAFE.filter(s => s < qi).pop();
    kept = safe != null ? PRIZES[safe] : 0;
  }
  const stars = reached >= 12 ? 3 : reached >= 8 ? 2 : reached >= 4 ? 1 : 0;
  saveStars('quiz', stars);
  const miss = log.find(x => !x.ok);
  const title = won ? 'Ти — справжній електрик! ⚡' : mode === 'take' ? 'Мудре рішення!' : 'Гру завершено';
  const text = `Правильних відповідей: <b>${reached} з ${N}</b>. Твій результат: <b>${kept} зі 100 балів</b>.` +
    (mode === 'take' ? ' Ти вчасно зупинився й забрав виграш.' : '') +
    (miss ? `<span class="miss">Питання, на якому ти спіткнувся: «${miss.q}». Правильна відповідь — <b>${miss.a}</b>.</span>` : '') +
    '<span class="miss">Наступного разу питання будуть інші!</span>';
  showResult({ stars, title, text, again: start });
}

document.getElementById('take').onclick = () => { if (!locked && score) finish('take'); };

// Клавіатура: 1–4 — відповідь, Enter — далі
document.addEventListener('keydown', e => {
  if (document.querySelector('.modal-bg') || locked) return;
  const idx = '1234'.indexOf(e.key);
  if (idx < 0) return;
  const b = card.querySelectorAll('.ans')[idx];
  if (b) answer(b);
});

start();
