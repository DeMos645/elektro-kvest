const card = document.getElementById('qcard');
const ladder = document.getElementById('ladder');
const lifeBox = document.getElementById('lifelines');
const cur = () => deck[qi][0]; // поточне питання

function start() {
  qi = 0; score = 0; locked = false; log = [];
  used = { fifty: false, hint: false, swap: SWAPS }; // swap — скільки замін питання ще лишилося
  miniTried = -1; // на якому питанні вже грали в міні-гру
  deck = POOL.map(p => shuffle(p)); // для кожної сходинки — випадковий порядок варіантів
  show();
}

function renderLadder() {
  ladder.innerHTML = PRIZES.map((p, i) =>
    `<div class="${i === qi ? 'cur' : i < qi ? 'passed' : ''} ${SAFE.includes(i) ? 'safe' : ''}">
      <span>${i + 1}</span><span>${SAFE.includes(i) ? '🔒 ' : ''}${p}</span></div>`).join('');
  document.getElementById('s-score').textContent = score;
  const take = document.getElementById('take');
  take.disabled = locked || score === 0;
  take.textContent = score ? `Забрати ${score} балів` : 'Забрати бали';
}

function renderLifelines() {
  lifeBox.innerHTML = `
    <button class="life" id="l-fifty" ${used.fifty ? 'disabled' : ''} title="Прибрати дві неправильні відповіді"><span>50:50</span><small>Прибрати дві</small></button>
    <button class="life" id="l-hint" ${used.hint ? 'disabled' : ''} title="Підказка викладача"><span>💡</span><small>Викладач</small></button>
    <button class="life" id="l-swap" ${used.swap ? '' : 'disabled'} title="Замінити питання іншим такої ж складності"><span>🔄 <em>×${used.swap}</em></span><small>Інше питання</small></button>
    ${canEarn() ? `<button class="earn" id="earn">⚡ Заробити підказку<small>Міні-гра «Правда чи міф?»</small></button>` : ''}`;
  document.getElementById('l-fifty').onclick = fifty;
  document.getElementById('l-hint').onclick = hint;
  document.getElementById('l-swap').onclick = swap;
  const earn = document.getElementById('earn');
  if (earn) earn.onclick = miniGame;
}

// Міні-гра доступна, якщо хоч одну підказку вже витрачено і на цьому питанні ще не грали
const canEarn = () => !locked && miniTried !== qi && (used.fifty || used.hint || used.swap < SWAPS);

function show() {
  locked = false;
  const Q = cur();
  const opts = shuffle([Q.a, ...Q.w]);
  card.innerHTML = `<div class="qhead"><span class="qnum">Питання ${qi + 1} з ${N}</span>
      <span class="qprize">${PRIZES[qi]} балів${SAFE.includes(qi) ? ' · 🔒 неспалима сума' : ''}</span></div>
    <div class="qbar"><i style="width:${qi / N * 100}%"></i></div>
    <div class="qtext">${Q.q}</div>
    ${Q.img ? `<div class="qimg">${Q.img}</div>` : ''}
    <div class="answers">${opts.map((o, i) => `<button class="ans" data-v="${o.replace(/"/g, '&quot;')}"><b>${'ABCD'[i]}</b><span>${o}</span></button>`).join('')}</div>
    <div id="extra"></div>`;
  card.classList.remove('enter'); void card.offsetWidth; card.classList.add('enter');
  card.querySelectorAll('.ans').forEach(b => b.onclick = () => answer(b));
  renderLadder();
  renderLifelines();
}

/* ---------- Підказки ---------- */
function fifty() {
  if (locked || used.fifty) return;
  used.fifty = true;
  const Q = cur();
  shuffle([...card.querySelectorAll('.ans:not(.hidden)')].filter(b => b.dataset.v !== Q.a)).slice(0, 2).forEach(b => b.classList.add('hidden'));
  renderLifelines();
}

function hint() {
  if (locked || used.hint) return;
  used.hint = true;
  document.getElementById('extra').innerHTML = `<div class="explain hint">💡 <b>Викладач підказує:</b> ${cur().hint}</div>`;
  renderLifelines();
}

// «Інше питання»: замінює поточне питання іншим варіантом тієї ж сходинки (варіанти йдуть по колу)
function swap() {
  if (locked || !used.swap || deck[qi].length < 2) return;
  used.swap--;
  deck[qi].push(deck[qi].shift());
  show();
}

